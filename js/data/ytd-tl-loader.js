// ─── PARSER (hem YTD_TL.csv hem YTD_KUTU.csv için ortak — yapıları aynı) ──
function parseYtdTlCSV(text) {
  const clean = String(text || '').replace(/^\uFEFF/, '').replace(/\r/g, '');
  const lines = clean.split('\n');
  const data = {};
  const order = [];

  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line || !line.trim()) { i++; continue; }
    const cols0 = line.split(';').map(s => s.trim());
    // Blok başlığı: "2026 YTD", "2026 1.DÖNEM", "2026 1.KOMPANZASYON" ...
    const m = cols0[0] && cols0[0].match(/^\d{4}\s+(.+)$/);
    if (m) {
      const periodKey = m[1].trim().toUpperCase();
      i++; // kolon başlık satırını (PERSONEL;HEDEF;SATIŞ;REAL;...) atla
      i++;
      const rows = [];
      while (i < lines.length) {
        const dl = lines[i];
        if (!dl || !dl.trim()) { i++; break; } // boş ayraç satırı → blok sonu
        const dcols = dl.split(';').map(s => s.trim());
        if (!dcols[0]) { i++; break; }
        const personel = dcols[0].toUpperCase();
        const products = {};
        YTD_TL_PRODUCT_KEYS.forEach((key, k) => {
          const base = 1 + 3 * k;
          products[key] = {
            hedef: typeof parseN === 'function' ? parseN(dcols[base])     : 0,
            satis: typeof parseN === 'function' ? parseN(dcols[base + 1]) : 0,
            real:  typeof parseN === 'function' ? parseN(dcols[base + 2]) : 0
          };
        });
        rows.push({ personel, products });
        i++;
      }
      if (rows.length) { data[periodKey] = rows; order.push(periodKey); }
      continue;
    }
    i++;
  }

  return { order, data };
}

// ─── YÜKLEME (fetch + fallback) — TL ve KUTU için ortak yardımcı ───────
async function _loadYtdBlockDataset(opts) {
  window.location; // no-op guard reference (keeps linters happy)
  opts.errorSet(null);

  // file:// altında fetch CORS ile engellenir → doğrudan gömülü veriye düş
  if (window.location.protocol === 'file:') {
    try {
      const parsed = parseYtdTlCSV(opts.embedded);
      opts.cacheSet(parsed);
      opts.errorSet('file://: GitHub\'dan taze veri çekilemedi, gömülü (statik) veri gösteriliyor.');
      return parsed;
    } catch (e) {
      opts.errorSet('Gömülü veri de okunamadı: ' + e.message);
      return null;
    }
  }

  try {
    const res = await fetch(opts.url + '?t=' + Date.now(), { cache: 'no-store' });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const text = await res.text();
    if (text.trim().startsWith('<')) throw new Error(opts.url + ' yerine HTML döndü');
    const parsed = parseYtdTlCSV(text);
    if (!parsed.order.length) throw new Error(opts.url + ' içinde geçerli dönem bloğu bulunamadı');
    opts.cacheSet(parsed);
    return parsed;
  } catch (e) {
    console.warn('[ytd-tl-loader] ' + opts.url + ' canlı çekilemedi, gömülü veriye düşülüyor:', e.message);
    try {
      const parsed = parseYtdTlCSV(opts.embedded);
      opts.cacheSet(parsed);
      opts.errorSet('Canlı veri çekilemedi (' + e.message + ') — gömülü (statik) veri gösteriliyor.');
      return parsed;
    } catch (e2) {
      opts.errorSet('Veri okunamadı: ' + e2.message);
      return null;
    }
  }
}

async function loadYtdTlData(forceFresh) {
  if (window.YTD_TL_DATA && !forceFresh) return window.YTD_TL_DATA;
  return _loadYtdBlockDataset({
    url: GS_YTD_TL_URL,
    embedded: YTD_TL_EMBEDDED_CSV,
    cacheSet: (v) => { window.YTD_TL_DATA = v; },
    errorSet: (e) => { window.YTD_TL_LOAD_ERROR = e; }
  });
}

async function loadYtdKutuData(forceFresh) {
  if (window.YTD_KUTU_DATA && !forceFresh) return window.YTD_KUTU_DATA;
  return _loadYtdBlockDataset({
    url: GS_YTD_KUTU_URL,
    embedded: YTD_KUTU_EMBEDDED_CSV,
    cacheSet: (v) => { window.YTD_KUTU_DATA = v; },
    errorSet: (e) => { window.YTD_KUTU_LOAD_ERROR = e; }
  });
}

// Her iki veri kaynağını birlikte yükler (sayfa ilk açıldığında çağrılır) —
// birim (TL/Kutu) anında, yeniden fetch etmeden değiştirilebilsin diye.
async function loadYtdAllData(forceFresh) {
  const [tl, kutu] = await Promise.all([
    loadYtdTlData(forceFresh),
    loadYtdKutuData(forceFresh)
  ]);
  return { tl, kutu };
}
